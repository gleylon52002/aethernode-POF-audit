// Domain -> hızlı O(1) arama seti.
const blockedSet: ReadonlySet<string> = new Set(BLOCKED_DOMAINS);

// Alan adının kendisi veya herhangi bir üst alan adı listede mi?
// "s.ad.doubleclick.net" -> ad.doubleclick.net -> doubleclick.net (eşleşir)
export function isBlockedDomain(hostname: string): boolean {
  let host = hostname.toLowerCase();
  if (host.endsWith('.')) host = host.slice(0, -1);
  while (host.length > 0) {
    if (blockedSet.has(host)) return true;
    const dot = host.indexOf('.');
    if (dot === -1) return false;
    host = host.slice(dot + 1);
  }
  return false;
}

export function blocklistSize(): number {
  return blockedSet.size;
}
